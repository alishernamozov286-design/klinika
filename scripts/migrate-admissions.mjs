/**
 * B6.2 (TZ §8.1.2, §10 "admissions"): inpatient stays and their bed periods.
 *
 *   npm run db:admissions
 *
 * Additive and safe to run again. **Run it before deploying the code that
 * reads it**: the bed board reads who lies where from these tables. Grants
 * admissions.manage to rahbar, registrator and hamshira (only ever adds).
 */
import { neonConfig, Pool } from "@neondatabase/serverless";
import ws from "ws";

try {
  process.loadEnvFile(".env");
} catch {
  // no .env — nothing to load
}

if (!process.env.DATABASE_URL) {
  console.error("DATABASE_URL topilmadi. Mahalliy JSON store o'zi yangilanadi.");
  process.exit(1);
}

neonConfig.webSocketConstructor = ws;
const pool = new Pool({ connectionString: process.env.DATABASE_URL });

// Kept in step with SYSTEM_ROLES in shared/permissions.ts.
const GRANTS = {
  rahbar: ["admissions.manage"],
  registrator: ["admissions.manage"],
  hamshira: ["admissions.manage"],
};

const client = await pool.connect();
try {
  await client.query("BEGIN");
  console.log("Jadvallar:");
  await client.query(`
    CREATE TABLE IF NOT EXISTS admissions (
      id                  varchar     PRIMARY KEY DEFAULT gen_random_uuid(),
      number              integer     GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL UNIQUE,
      patient_id          varchar     NOT NULL REFERENCES patients (id),
      department_id       varchar     NOT NULL REFERENCES departments (id),
      doctor_id           varchar     NOT NULL REFERENCES doctors (id),
      admitted_at         timestamptz NOT NULL,
      reason              text,
      status              text        NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'discharged', 'cancelled')),
      cancelled_at        timestamptz,
      cancelled_by        varchar,
      cancelled_by_name   text,
      cancel_reason       text,
      discharged_at       timestamptz,
      discharged_by       varchar,
      discharged_by_name  text,
      created_at          timestamptz NOT NULL DEFAULT now(),
      created_by          varchar,
      created_by_name     text,
      updated_at          timestamptz,
      updated_by          varchar,
      -- Each status carries exactly the marks of how it got there.
      CONSTRAINT "CK_admissions_status" CHECK (
        (cancelled_at IS NOT NULL) = (status = 'cancelled')
        AND (cancelled_at IS NULL OR cancel_reason IS NOT NULL)
        AND (discharged_at IS NOT NULL) = (status = 'discharged')
      )
    )`);
  // One active stay per patient — two registrars at once still make one.
  await client.query(`CREATE UNIQUE INDEX IF NOT EXISTS "UQ_admissions_active_patient" ON admissions (patient_id) WHERE status = 'active'`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_admissions_status" ON admissions (status)`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_admissions_patient" ON admissions (patient_id)`);
  console.log("  ok  admissions (bemorga bitta faol yotqizish)");
  await client.query(`
    CREATE TABLE IF NOT EXISTS admission_beds (
      id             varchar     PRIMARY KEY DEFAULT gen_random_uuid(),
      admission_id   varchar     NOT NULL REFERENCES admissions (id),
      bed_id         varchar     NOT NULL REFERENCES beds (id),
      ward_id        varchar     NOT NULL REFERENCES wards (id),
      from_at        timestamptz NOT NULL,
      to_at          timestamptz,
      note           text,
      moved_by       varchar,
      moved_by_name  text,
      CONSTRAINT "CK_admission_beds_period" CHECK (to_at IS NULL OR to_at >= from_at)
    )`);
  // One patient per bed, one bed per stay, at any moment.
  await client.query(`CREATE UNIQUE INDEX IF NOT EXISTS "UQ_admission_beds_open_bed" ON admission_beds (bed_id) WHERE to_at IS NULL`);
  await client.query(`CREATE UNIQUE INDEX IF NOT EXISTS "UQ_admission_beds_open_admission" ON admission_beds (admission_id) WHERE to_at IS NULL`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_admission_beds_admission" ON admission_beds (admission_id)`);
  console.log("  ok  admission_beds (yotoqda bitta bemor)");

  console.log("\nRuxsatlar:");
  const { rows: hasRoles } = await client.query(`SELECT to_regclass('public.roles') IS NOT NULL AS ok`);
  if (!hasRoles[0].ok) {
    console.log("  —   roles jadvali yo'q (avval npm run db:roles); standart rollar koddan olinadi");
  } else {
    for (const [key, perms] of Object.entries(GRANTS)) {
      const { rows } = await client.query(
        `UPDATE roles
            SET permissions = ARRAY(SELECT DISTINCT unnest(permissions || $2::text[]) ORDER BY 1)
          WHERE key = $1 AND is_system AND NOT (permissions @> $2::text[])
          RETURNING key`,
        [key, perms],
      );
      console.log(`  ${rows.length ? "ok " : "—  "} ${key}: ${perms.join(", ")}${rows.length ? "" : " (allaqachon bor)"}`);
    }
  }

  await client.query("COMMIT");
  console.log("\nTayyor.");
} catch (err) {
  await client.query("ROLLBACK");
  console.error("Xato, hech narsa o'zgarmadi:", err.message);
  process.exitCode = 1;
} finally {
  client.release();
  await pool.end();
}
