/**
 * B7.5 (TZ §9.2 "Kassa smenasini yopish"): cash shifts, and the shift every
 * payment is recorded in.
 *
 *   npm run db:cash-shifts
 *
 * Additive and safe to run again. **Run it before deploying the code that
 * reads it**: every payment insert now names `shift_id`. Existing payments
 * keep shift_id NULL (taken before shifts existed) and stay voidable as before.
 * Grants shifts.read / shifts.manage to the system roles (only ever adds).
 */
import { neonConfig, Pool } from "@neondatabase/serverless";
import ws from "ws";

try {
  process.loadEnvFile(".env");
} catch {
  // no .env — nothing to load
}

if (!process.env.DATABASE_URL) {
  console.error("DATABASE_URL topilmadi. Mahalliy JSON store o'zi yangilanadi.");
  process.exit(1);
}

neonConfig.webSocketConstructor = ws;
const pool = new Pool({ connectionString: process.env.DATABASE_URL });

// Kept in step with SYSTEM_ROLES in shared/permissions.ts.
const GRANTS = {
  rahbar: ["shifts.read", "shifts.manage"],
  buxgalter: ["shifts.read"],
  auditor: ["shifts.read"],
};

const client = await pool.connect();
try {
  await client.query("BEGIN");
  console.log("Jadval:");
  await client.query(`
    CREATE TABLE IF NOT EXISTS cash_shifts (
      id              varchar     PRIMARY KEY DEFAULT gen_random_uuid(),
      number          integer     GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL UNIQUE,
      cashier_id      varchar     NOT NULL,
      cashier_name    text        NOT NULL,
      opened_at       timestamptz NOT NULL DEFAULT now(),
      opening_cash    integer     NOT NULL DEFAULT 0 CHECK (opening_cash >= 0),
      opening_note    text,
      closed_at       timestamptz,
      closed_by       varchar,
      closed_by_name  text,
      expected_cash   integer,
      counted_cash    integer     CHECK (counted_cash >= 0),
      difference      integer,
      carried_cash    integer     CHECK (carried_cash >= 0),
      denominations   json,
      closing_note    text,
      totals          json,
      -- Open: nothing of the closing is set. Closed: all of it is, and it adds up.
      CONSTRAINT "CK_cash_shifts_closed" CHECK (
        CASE WHEN closed_at IS NULL
          THEN closed_by_name IS NULL AND expected_cash IS NULL AND counted_cash IS NULL AND difference IS NULL
               AND carried_cash IS NULL AND totals IS NULL AND closing_note IS NULL
          ELSE closed_by_name IS NOT NULL AND expected_cash IS NOT NULL AND counted_cash IS NOT NULL AND carried_cash IS NOT NULL
               AND totals IS NOT NULL AND difference = counted_cash - expected_cash AND carried_cash <= counted_cash
        END)
    )`);
  await client.query(`CREATE UNIQUE INDEX IF NOT EXISTS "UQ_cash_shifts_open" ON cash_shifts (cashier_id) WHERE closed_at IS NULL`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_cash_shifts_opened" ON cash_shifts (opened_at)`);
  console.log("  ok  cash_shifts (bir xodimga bitta ochiq smena)");

  console.log("\nTo'lovlar:");
  await client.query(`ALTER TABLE payments ADD COLUMN IF NOT EXISTS shift_id varchar REFERENCES cash_shifts (id)`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_payments_shift" ON payments (shift_id) WHERE shift_id IS NOT NULL`);
  console.log("  ok  payments.shift_id");

  console.log("\nRuxsatlar:");
  const { rows: hasRoles } = await client.query(`SELECT to_regclass('public.roles') IS NOT NULL AS ok`);
  if (!hasRoles[0].ok) {
    console.log("  —   roles jadvali yo'q (avval npm run db:roles); standart rollar koddan olinadi");
  } else {
    for (const [key, perms] of Object.entries(GRANTS)) {
      const { rows } = await client.query(
        `UPDATE roles
            SET permissions = ARRAY(SELECT DISTINCT unnest(permissions || $2::text[]) ORDER BY 1)
          WHERE key = $1 AND is_system AND NOT (permissions @> $2::text[])
          RETURNING key`,
        [key, perms],
      );
      console.log(`  ${rows.length ? "ok " : "—  "} ${key}: ${perms.join(", ")}${rows.length ? "" : " (allaqachon bor)"}`);
    }
  }

  await client.query("COMMIT");
  console.log("\nTayyor.");
} catch (err) {
  await client.query("ROLLBACK");
  console.error("Xato, hech narsa o'zgarmadi:", err.message);
  process.exitCode = 1;
} finally {
  client.release();
  await pool.end();
}
