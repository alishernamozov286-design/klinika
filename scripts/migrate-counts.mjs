/**
 * B5.5 (TZ §7.1): inventarizatsiya — stock counts, their lines, and the link
 * from each correcting stock movement to its count.
 *
 *   npm run db:counts
 *
 * Additive and safe to run again. **Run it before deploying the code that
 * reads it**: every stock movement insert now names `count_id`, and
 * cancelling a receipt or an issue checks the count lines. Grants are only added.
 */
import { neonConfig, Pool } from "@neondatabase/serverless";
import ws from "ws";

try {
  process.loadEnvFile(".env");
} catch {
  // no .env — nothing to load
}

if (!process.env.DATABASE_URL) {
  console.error("DATABASE_URL topilmadi. Mahalliy JSON store o'zi yangilanadi.");
  process.exit(1);
}

neonConfig.webSocketConstructor = ws;
const pool = new Pool({ connectionString: process.env.DATABASE_URL });

// Kept in step with SYSTEM_ROLES in shared/permissions.ts.
const GRANTS = {
  omborchi: ["inventory.count"],
};

const client = await pool.connect();
try {
  await client.query("BEGIN");
  console.log("Jadvallar:");
  await client.query(`
    CREATE TABLE IF NOT EXISTS stock_counts (
      id                 varchar     PRIMARY KEY DEFAULT gen_random_uuid(),
      number             integer     GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL UNIQUE,
      status             text        NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'posted', 'cancelled')),
      kinds              text[],
      counted_on         text        NOT NULL,
      notes              text,
      shortage_value     integer     NOT NULL DEFAULT 0 CHECK (shortage_value >= 0),
      surplus_value      integer     NOT NULL DEFAULT 0 CHECK (surplus_value >= 0),
      created_at         timestamptz NOT NULL DEFAULT now(),
      created_by         varchar,
      created_by_name    text,
      posted_at          timestamptz,
      posted_by          varchar,
      posted_by_name     text,
      cancelled_at       timestamptz,
      cancelled_by       varchar,
      cancelled_by_name  text,
      cancel_reason      text,
      CONSTRAINT "CK_stock_counts_state" CHECK (
        (status = 'open' AND posted_at IS NULL AND cancelled_at IS NULL) OR
        (status = 'posted' AND posted_at IS NOT NULL AND cancelled_at IS NULL) OR
        (status = 'cancelled' AND cancelled_at IS NOT NULL AND posted_at IS NULL AND cancel_reason IS NOT NULL)
      )
    )`);
  // One open count at a time: two counts over the same shelf would each post the same difference.
  await client.query(`CREATE UNIQUE INDEX IF NOT EXISTS "UQ_stock_counts_open" ON stock_counts (status) WHERE status = 'open'`);
  console.log("  ok  stock_counts");
  await client.query(`
    CREATE TABLE IF NOT EXISTS stock_count_lines (
      id               varchar          PRIMARY KEY DEFAULT gen_random_uuid(),
      count_id         varchar          NOT NULL REFERENCES stock_counts (id),
      item_id          varchar          NOT NULL,
      batch_id         varchar          NOT NULL,
      expected         double precision NOT NULL CHECK (expected >= 0),
      counted          double precision CHECK (counted >= 0),
      note             text,
      counted_at       timestamptz,
      counted_by       varchar,
      counted_by_name  text,
      CONSTRAINT "CK_stock_count_lines_counted" CHECK ((counted IS NULL) = (counted_at IS NULL))
    )`);
  await client.query(`CREATE UNIQUE INDEX IF NOT EXISTS "UQ_stock_count_lines_batch" ON stock_count_lines (count_id, batch_id)`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_stock_count_lines_batch" ON stock_count_lines (batch_id)`);
  console.log("  ok  stock_count_lines");
  await client.query(`ALTER TABLE stock_movements ADD COLUMN IF NOT EXISTS count_id varchar`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_stock_movements_count" ON stock_movements (count_id) WHERE count_id IS NOT NULL`);
  console.log("  ok  stock_movements.count_id");

  console.log("\nRuxsatlar:");
  const hasRoles = (await client.query(`SELECT to_regclass('public.roles') IS NOT NULL AS ok`)).rows[0].ok;
  if (!hasRoles) {
    console.log("  —   roles jadvali yo'q (avval npm run db:roles); standart rollar koddan olinadi");
  } else {
    for (const [key, perms] of Object.entries(GRANTS)) {
      const { rows } = await client.query(
        `UPDATE roles
            SET permissions = ARRAY(SELECT DISTINCT unnest(permissions || $2::text[]) ORDER BY 1)
          WHERE key = $1 AND is_system AND NOT (permissions @> $2::text[])
          RETURNING key`,
        [key, perms],
      );
      console.log(`  ${rows.length ? "ok " : "—  "} ${key}: ${perms.join(", ")}${rows.length ? "" : " (allaqachon bor)"}`);
    }
  }

  await client.query("COMMIT");
  console.log("\nTayyor.");
} catch (err) {
  await client.query("ROLLBACK");
  console.error("Xato, hech narsa o'zgarmadi:", err.message);
  process.exitCode = 1;
} finally {
  client.release();
  await pool.end();
}
