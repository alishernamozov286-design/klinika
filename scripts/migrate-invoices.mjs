/**
 * B7.1 (TZ §9.1, §9.2, §10 "invoices"): bills per visit, their receipts, and
 * payments that pay an appointment as well as a lab order.
 *
 *   npm run db:invoices
 *
 * Additive and safe to run again. **Run it before deploying the code that
 * reads it**: every payment insert now names `appointment_id` and
 * `invoice_payment_id`. Existing payments keep their order and gain nothing;
 * the new CHECK holds for them (each pays exactly one order). No new
 * permissions: payments.create / payments.delete / finance.view as before.
 */
import { neonConfig, Pool } from "@neondatabase/serverless";
import ws from "ws";

try {
  process.loadEnvFile(".env");
} catch {
  // no .env — nothing to load
}

if (!process.env.DATABASE_URL) {
  console.error("DATABASE_URL topilmadi. Mahalliy JSON store o'zi yangilanadi.");
  process.exit(1);
}

neonConfig.webSocketConstructor = ws;
const pool = new Pool({ connectionString: process.env.DATABASE_URL });

const client = await pool.connect();
try {
  await client.query("BEGIN");
  console.log("Jadvallar:");
  await client.query(`
    CREATE TABLE IF NOT EXISTS invoices (
      id               varchar     PRIMARY KEY DEFAULT gen_random_uuid(),
      number           integer     GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL UNIQUE,
      patient_id       varchar     NOT NULL,
      visit_id         varchar     NOT NULL,
      created_at       timestamptz NOT NULL DEFAULT now(),
      created_by       varchar,
      created_by_name  text
    )`);
  await client.query(`CREATE UNIQUE INDEX IF NOT EXISTS "UQ_invoices_visit" ON invoices (visit_id)`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_invoices_patient" ON invoices (patient_id)`);
  console.log("  ok  invoices");
  await client.query(`
    CREATE TABLE IF NOT EXISTS invoice_payments (
      id                varchar     PRIMARY KEY DEFAULT gen_random_uuid(),
      number            integer     GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL UNIQUE,
      invoice_id        varchar     NOT NULL REFERENCES invoices (id),
      patient_id        varchar     NOT NULL,
      amount            integer     NOT NULL CHECK (amount > 0),
      method            text        NOT NULL DEFAULT 'naqd' CHECK (method IN ('naqd', 'karta', 'o''tkazma')),
      note              text,
      created_at        timestamptz NOT NULL DEFAULT now(),
      created_by        varchar,
      created_by_name   text,
      voided_at         timestamptz,
      voided_by         varchar,
      voided_by_name    text,
      void_reason       text,
      CONSTRAINT "CK_invoice_payments_void" CHECK ((voided_at IS NULL) = (void_reason IS NULL))
    )`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_invoice_payments_invoice" ON invoice_payments (invoice_id)`);
  console.log("  ok  invoice_payments");

  console.log("\nTo'lovlar:");
  await client.query(`ALTER TABLE payments ALTER COLUMN order_id DROP NOT NULL`);
  await client.query(`ALTER TABLE payments ADD COLUMN IF NOT EXISTS appointment_id varchar`);
  await client.query(`ALTER TABLE payments ADD COLUMN IF NOT EXISTS invoice_payment_id varchar`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_payments_appointment" ON payments (appointment_id) WHERE appointment_id IS NOT NULL`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_payments_invoice_payment" ON payments (invoice_payment_id) WHERE invoice_payment_id IS NOT NULL`);
  // A payment pays exactly one thing: an order or an appointment.
  await client.query(`
    DO $$ BEGIN
      IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'CK_payments_target') THEN
        ALTER TABLE payments ADD CONSTRAINT "CK_payments_target"
          CHECK ((order_id IS NOT NULL)::int + (appointment_id IS NOT NULL)::int = 1);
      END IF;
    END $$`);
  console.log("  ok  payments.order_id ixtiyoriy, appointment_id, invoice_payment_id, CK_payments_target");

  await client.query("COMMIT");
  console.log("\nTayyor.");
} catch (err) {
  await client.query("ROLLBACK");
  console.error("Xato, hech narsa o'zgarmadi:", err.message);
  process.exitCode = 1;
} finally {
  client.release();
  await pool.end();
}
