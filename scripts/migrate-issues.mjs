/**
 * B5.3 (TZ §7.1, §7.3): issue documents — to a department or written off —
 * and the link from each outgoing stock movement to its document.
 *
 *   npm run db:issues
 *
 * Additive and safe to run again. **Run it before deploying the code that
 * reads it**: every stock movement insert now names `issue_id`, receipts
 * included. Grants are only added.
 */
import { neonConfig, Pool } from "@neondatabase/serverless";
import ws from "ws";

try {
  process.loadEnvFile(".env");
} catch {
  // no .env — nothing to load
}

if (!process.env.DATABASE_URL) {
  console.error("DATABASE_URL topilmadi. Mahalliy JSON store o'zi yangilanadi.");
  process.exit(1);
}

neonConfig.webSocketConstructor = ws;
const pool = new Pool({ connectionString: process.env.DATABASE_URL });

// Kept in step with SYSTEM_ROLES in shared/permissions.ts.
const GRANTS = {
  omborchi: ["inventory.issue"],
};

const client = await pool.connect();
try {
  await client.query("BEGIN");
  console.log("Jadvallar:");
  await client.query(`
    CREATE TABLE IF NOT EXISTS stock_issues (
      id                 varchar     PRIMARY KEY DEFAULT gen_random_uuid(),
      number             integer     GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL UNIQUE,
      kind               text        NOT NULL CHECK (kind IN ('department', 'writeoff')),
      department_id      varchar,
      received_by        text,
      reason             text,
      issued_on          text        NOT NULL,
      notes              text,
      total              integer     NOT NULL DEFAULT 0 CHECK (total >= 0),
      created_at         timestamptz NOT NULL DEFAULT now(),
      created_by         varchar,
      created_by_name    text,
      cancelled_at       timestamptz,
      cancelled_by       varchar,
      cancelled_by_name  text,
      cancel_reason      text,
      CONSTRAINT "CK_stock_issues_target" CHECK (
        (kind = 'department' AND department_id IS NOT NULL) OR (kind = 'writeoff' AND reason IS NOT NULL)
      )
    )`);
  console.log("  ok  stock_issues");
  await client.query(`ALTER TABLE stock_movements ADD COLUMN IF NOT EXISTS issue_id varchar`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_stock_movements_issue" ON stock_movements (issue_id) WHERE issue_id IS NOT NULL`);
  console.log("  ok  stock_movements.issue_id");

  console.log("\nRuxsatlar:");
  const hasRoles = (await client.query(`SELECT to_regclass('public.roles') IS NOT NULL AS ok`)).rows[0].ok;
  if (!hasRoles) {
    console.log("  —   roles jadvali yo'q (avval npm run db:roles); standart rollar koddan olinadi");
  } else {
    for (const [key, perms] of Object.entries(GRANTS)) {
      const { rows } = await client.query(
        `UPDATE roles
            SET permissions = ARRAY(SELECT DISTINCT unnest(permissions || $2::text[]) ORDER BY 1)
          WHERE key = $1 AND is_system AND NOT (permissions @> $2::text[])
          RETURNING key`,
        [key, perms],
      );
      console.log(`  ${rows.length ? "ok " : "—  "} ${key}: ${perms.join(", ")}${rows.length ? "" : " (allaqachon bor)"}`);
    }
  }

  await client.query("COMMIT");
  console.log("\nTayyor.");
} catch (err) {
  await client.query("ROLLBACK");
  console.error("Xato, hech narsa o'zgarmadi:", err.message);
  process.exitCode = 1;
} finally {
  client.release();
  await pool.end();
}
