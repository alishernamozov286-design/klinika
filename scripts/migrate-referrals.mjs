/**
 * B3.5 (TZ §5.1.4, §11): doctors' referrals — to the lab, to examinations and
 * to specialists — and the links from the lab order and the booking that
 * fulfil them. Plus the permissions that open them.
 *
 *   npm run db:referrals
 *
 * Run it BEFORE deploying the code that needs it: that code reads
 * orders.referral_id and appointments.referral_id on every order and booking
 * query. The old code ignores them, so running it early is harmless.
 *
 * Additive and safe to run again, in one transaction. It only ever adds
 * permissions to the built-in roles; nothing else in a role is touched.
 */
import { neonConfig, Pool } from "@neondatabase/serverless";
import ws from "ws";

try {
  process.loadEnvFile(".env");
} catch {
  // no .env — nothing to load
}

if (!process.env.DATABASE_URL) {
  console.error("DATABASE_URL topilmadi. Mahalliy JSON store o'zi yangilanadi.");
  process.exit(1);
}

neonConfig.webSocketConstructor = ws;
const pool = new Pool({ connectionString: process.env.DATABASE_URL });

// Kept in step with SYSTEM_ROLES in shared/permissions.ts.
const GRANTS = {
  shifokor: ["referrals.read", "referrals.create"],
  registrator: ["referrals.read", "referrals.manage"],
  rahbar: ["referrals.read"],
  auditor: ["referrals.read"],
};

const client = await pool.connect();
try {
  await client.query("BEGIN");
  console.log("Jadvallar:");
  await client.query(`
    CREATE TABLE IF NOT EXISTS referrals (
      id                varchar     PRIMARY KEY DEFAULT gen_random_uuid(),
      referral_number   integer     GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
      patient_id        varchar     NOT NULL,
      visit_id          varchar,
      appointment_id    varchar,
      doctor_id         varchar     NOT NULL,
      kind              text        NOT NULL,
      status            text        NOT NULL DEFAULT 'active',
      service_id        varchar,
      target_specialty  text,
      target_doctor_id  varchar,
      note              text,
      created_at        timestamptz NOT NULL DEFAULT now(),
      created_by        varchar,
      updated_at        timestamptz,
      updated_by        varchar,
      cancelled_at      timestamptz,
      cancelled_by      varchar,
      cancel_reason     text
    )`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_referrals_patient" ON referrals (patient_id)`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_referrals_appointment" ON referrals (appointment_id)`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_referrals_status_kind" ON referrals (status, kind)`);
  console.log("  ok  referrals");

  await client.query(`ALTER TABLE orders ADD COLUMN IF NOT EXISTS referral_id varchar`);
  // A lab referral becomes exactly one order.
  await client.query(`CREATE UNIQUE INDEX IF NOT EXISTS "UQ_orders_referral" ON orders (referral_id) WHERE referral_id IS NOT NULL`);
  console.log("  ok  orders.referral_id");

  const hasAppointments = (await client.query(`SELECT to_regclass('public.appointments') IS NOT NULL AS ok`)).rows[0].ok;
  if (hasAppointments) {
    await client.query(`ALTER TABLE appointments ADD COLUMN IF NOT EXISTS referral_id varchar`);
    // One live booking per referral: two registrars cannot book it twice.
    await client.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS "UQ_appointments_referral" ON appointments (referral_id)
      WHERE referral_id IS NOT NULL AND status NOT IN ('cancelled', 'no_show')`);
    console.log("  ok  appointments.referral_id");
  } else {
    console.log("  —   appointments jadvali yo'q (avval npm run db:appointments)");
  }

  console.log("\nRuxsatlar:");
  const hasRoles = (await client.query(`SELECT to_regclass('public.roles') IS NOT NULL AS ok`)).rows[0].ok;
  if (!hasRoles) {
    console.log("  —   roles jadvali yo'q (avval npm run db:roles); standart rollar koddan olinadi");
  } else {
    for (const [key, perms] of Object.entries(GRANTS)) {
      const { rows } = await client.query(
        `UPDATE roles
            SET permissions = ARRAY(SELECT DISTINCT unnest(permissions || $2::text[]) ORDER BY 1)
          WHERE key = $1 AND is_system AND NOT (permissions @> $2::text[])
          RETURNING key`,
        [key, perms],
      );
      console.log(`  ${rows.length ? "ok " : "—  "} ${key}: ${perms.join(", ")}${rows.length ? "" : " (allaqachon bor)"}`);
    }
  }

  await client.query("COMMIT");
  console.log("\nTayyor.");
} catch (err) {
  await client.query("ROLLBACK");
  console.error("Xato, hech narsa o'zgarmadi:", err.message);
  process.exitCode = 1;
} finally {
  client.release();
  await pool.end();
}
