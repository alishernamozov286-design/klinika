/**
 * B7.4 (TZ §9.2 "To'lov qaytarish faqat vakolatli shaxs tasdig'i bilan
 * bajariladi", §9.1 "Qaytarilgan to'lovlar"): refund requests, their approval
 * and their payout, and the payments rows that pay them out.
 *
 *   npm run db:refunds
 *
 * Additive and safe to run again. **Run it before deploying the code that
 * reads it**: every payment insert now names `refund_id`, and every bill reads
 * its refunds. Existing payments keep refund_id NULL. No new permissions:
 * payments.create asks and pays, payments.refund approves.
 */
import { neonConfig, Pool } from "@neondatabase/serverless";
import ws from "ws";

try {
  process.loadEnvFile(".env");
} catch {
  // no .env — nothing to load
}

if (!process.env.DATABASE_URL) {
  console.error("DATABASE_URL topilmadi. Mahalliy JSON store o'zi yangilanadi.");
  process.exit(1);
}

neonConfig.webSocketConstructor = ws;
const pool = new Pool({ connectionString: process.env.DATABASE_URL });

const client = await pool.connect();
try {
  await client.query("BEGIN");
  console.log("Jadval:");
  await client.query(`
    CREATE TABLE IF NOT EXISTS refunds (
      id                 varchar     PRIMARY KEY DEFAULT gen_random_uuid(),
      number             integer     GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL UNIQUE,
      patient_id         varchar     NOT NULL,
      visit_id           varchar     NOT NULL,
      amount             integer     NOT NULL CHECK (amount > 0),
      method             text        NOT NULL DEFAULT 'naqd' CHECK (method IN ('naqd', 'karta', 'o''tkazma')),
      reason             text        NOT NULL CHECK (length(btrim(reason)) >= 5),
      status             text        NOT NULL DEFAULT 'requested' CHECK (status IN ('requested', 'approved', 'paid', 'rejected', 'cancelled')),
      requested_at       timestamptz NOT NULL DEFAULT now(),
      requested_by       varchar,
      requested_by_name  text,
      decided_at         timestamptz,
      decided_by         varchar,
      decided_by_name    text,
      decision_note      text,
      paid_at            timestamptz,
      paid_by            varchar,
      paid_by_name       text,
      shift_id           varchar     REFERENCES cash_shifts (id),
      lines              json,
      cancelled_at       timestamptz,
      cancelled_by       varchar,
      cancelled_by_name  text,
      cancel_reason      text,
      print_count        integer     NOT NULL DEFAULT 0 CHECK (print_count >= 0),
      -- Each status carries exactly the marks of how it got there.
      CONSTRAINT "CK_refunds_flow" CHECK (
        (decided_at IS NOT NULL) = (status IN ('approved', 'paid', 'rejected') OR (status = 'cancelled' AND decided_at IS NOT NULL))
        AND (paid_at IS NOT NULL) = (status = 'paid')
        AND (status <> 'paid' OR lines IS NOT NULL)
        AND (cancelled_at IS NOT NULL) = (status = 'cancelled')
        AND (cancelled_at IS NULL OR cancel_reason IS NOT NULL)
        AND (status <> 'rejected' OR decision_note IS NOT NULL)
        AND (decided_by IS NULL OR requested_by IS NULL OR decided_by <> requested_by)
      )
    )`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_refunds_visit" ON refunds (visit_id)`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_refunds_status" ON refunds (status)`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_refunds_patient" ON refunds (patient_id)`);
  console.log("  ok  refunds (so'rov → tasdiq → to'lov; tasdiqlovchi so'ragan xodim emas)");

  console.log("\nTo'lovlar:");
  await client.query(`ALTER TABLE payments ADD COLUMN IF NOT EXISTS refund_id varchar REFERENCES refunds (id)`);
  await client.query(`CREATE INDEX IF NOT EXISTS "IDX_payments_refund" ON payments (refund_id) WHERE refund_id IS NOT NULL`);
  // A payout row hands money back: always negative.
  await client.query(`
    DO $$ BEGIN
      IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'CK_payments_refund') THEN
        ALTER TABLE payments ADD CONSTRAINT "CK_payments_refund" CHECK (refund_id IS NULL OR amount < 0);
      END IF;
    END $$`);
  console.log("  ok  payments.refund_id, CK_payments_refund");

  await client.query("COMMIT");
  console.log("\nTayyor.");
} catch (err) {
  await client.query("ROLLBACK");
  console.error("Xato, hech narsa o'zgarmadi:", err.message);
  process.exitCode = 1;
} finally {
  client.release();
  await pool.end();
}
