/**
 * B5.2 (TZ §7.3): receipts, batches (LOT, expiry, purchase price) and the
 * stock movement ledger.
 *
 *   npm run db:stock
 *
 * Additive and safe to run again. **Run it before deploying the code that
 * reads it**: the catalogue sums batches for "on hand" (it falls back to zero
 * without the table, but receipts need it). Grants are only added.
 */
import { neonConfig, Pool } from "@neondatabase/serverless";
import ws from "ws";

try {
  process.loadEnvFile(".env");
} catch {
  // no .env — nothing to load
}

if (!process.env.DATABASE_URL) {
  console.error("DATABASE_URL topilmadi. Mahalliy JSON store o'zi yangilanadi.");
  process.exit(1);
}

neonConfig.webSocketConstructor = ws;
const pool = new Pool({ connectionString: process.env.DATABASE_URL });

// Kept in step with SYSTEM_ROLES in shared/permissions.ts.
const GRANTS = {
  omborchi: ["inventory.receive"],
};

const TABLES = {
  stock_receipts: `
    CREATE TABLE IF NOT EXISTS stock_receipts (
      id                 varchar     PRIMARY KEY DEFAULT gen_random_uuid(),
      number             integer     GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL UNIQUE,
      supplier           text        NOT NULL,
      document_number    text,
      received_on        text        NOT NULL,
      notes              text,
      total              integer     NOT NULL DEFAULT 0 CHECK (total >= 0),
      created_at         timestamptz NOT NULL DEFAULT now(),
      created_by         varchar,
      created_by_name    text,
      cancelled_at       timestamptz,
      cancelled_by       varchar,
      cancelled_by_name  text,
      cancel_reason      text
    )`,
  inventory_batches: `
    CREATE TABLE IF NOT EXISTS inventory_batches (
      id              varchar          PRIMARY KEY DEFAULT gen_random_uuid(),
      item_id         varchar          NOT NULL,
      receipt_id      varchar          NOT NULL,
      lot_number      text,
      expires_on      text,
      quantity        double precision NOT NULL CHECK (quantity > 0),
      remaining       double precision NOT NULL,
      purchase_price  integer          NOT NULL CHECK (purchase_price >= 0),
      created_at      timestamptz      NOT NULL DEFAULT now(),
      cancelled_at    timestamptz,
      CONSTRAINT "CK_inventory_batches_remaining" CHECK (remaining >= 0 AND remaining <= quantity)
    )`,
  stock_movements: `
    CREATE TABLE IF NOT EXISTS stock_movements (
      id               varchar          PRIMARY KEY DEFAULT gen_random_uuid(),
      item_id          varchar          NOT NULL,
      batch_id         varchar          NOT NULL,
      kind             text             NOT NULL,
      quantity         double precision NOT NULL CHECK (quantity <> 0),
      receipt_id       varchar,
      note             text,
      created_at       timestamptz      NOT NULL DEFAULT now(),
      created_by       varchar,
      created_by_name  text
    )`,
};

const INDEXES = [
  `CREATE INDEX IF NOT EXISTS "IDX_inventory_batches_item" ON inventory_batches (item_id)`,
  `CREATE INDEX IF NOT EXISTS "IDX_inventory_batches_receipt" ON inventory_batches (receipt_id)`,
  `CREATE INDEX IF NOT EXISTS "IDX_stock_movements_item" ON stock_movements (item_id, created_at)`,
];

const client = await pool.connect();
try {
  await client.query("BEGIN");
  console.log("Jadvallar:");
  for (const [name, ddl] of Object.entries(TABLES)) {
    await client.query(ddl);
    console.log(`  ok  ${name}`);
  }
  for (const ddl of INDEXES) await client.query(ddl);
  console.log("  ok  indekslar");

  console.log("\nRuxsatlar:");
  const hasRoles = (await client.query(`SELECT to_regclass('public.roles') IS NOT NULL AS ok`)).rows[0].ok;
  if (!hasRoles) {
    console.log("  —   roles jadvali yo'q (avval npm run db:roles); standart rollar koddan olinadi");
  } else {
    for (const [key, perms] of Object.entries(GRANTS)) {
      const { rows } = await client.query(
        `UPDATE roles
            SET permissions = ARRAY(SELECT DISTINCT unnest(permissions || $2::text[]) ORDER BY 1)
          WHERE key = $1 AND is_system AND NOT (permissions @> $2::text[])
          RETURNING key`,
        [key, perms],
      );
      console.log(`  ${rows.length ? "ok " : "—  "} ${key}: ${perms.join(", ")}${rows.length ? "" : " (allaqachon bor)"}`);
    }
  }

  await client.query("COMMIT");
  console.log("\nTayyor.");
} catch (err) {
  await client.query("ROLLBACK");
  console.error("Xato, hech narsa o'zgarmadi:", err.message);
  process.exitCode = 1;
} finally {
  client.release();
  await pool.end();
}
