import { describe, expect, it } from "vitest";
import { BACKUP_FORMAT, columnDdl, openBackup, sealBackup, type BackupFile } from "./backup-core";

const sample: BackupFile = {
  format: BACKUP_FORMAT,
  version: 1,
  createdAt: "2026-11-24T02:30:00.000Z",
  server: "17.12",
  tables: [
    {
      name: "patients",
      columns: [
        { name: "id", type: "character varying", notNull: true, default: "gen_random_uuid()", identity: "" },
        { name: "patient_number", type: "integer", notNull: true, default: null, identity: "d" },
      ],
      constraints: [{ name: "patients_pkey", kind: "p", def: "PRIMARY KEY (id)" }],
      indexes: [],
      rowCount: 1,
      checksum: "abc",
      rows: [{ id: "p1", patient_number: 1, full_name: "Normatov Aziz" }],
    },
  ],
};

describe("backup file (B8.3)", () => {
  it("seals and opens: compressed, encrypted, the same content back", () => {
    const sealed = sealBackup(sample, "a-strong-passphrase");
    expect(sealed.subarray(0, 5).toString()).toBe("MLBK1");
    // Encrypted: the patient's name is not in the bytes.
    expect(sealed.includes(Buffer.from("Normatov"))).toBe(false);
    expect(openBackup(sealed, "a-strong-passphrase")).toEqual(sample);
    // Each seal is different (fresh salt and IV).
    expect(sealBackup(sample, "a-strong-passphrase").equals(sealed)).toBe(false);
  });

  it("refuses a wrong passphrase, a tampered file, a stranger's file and a weak passphrase", () => {
    const sealed = sealBackup(sample, "a-strong-passphrase");
    expect(() => openBackup(sealed, "another-passphrase")).toThrow(/paroli noto'g'ri/);
    const tampered = Buffer.from(sealed);
    tampered[tampered.length - 1] ^= 1;
    expect(() => openBackup(tampered, "a-strong-passphrase")).toThrow(/buzilgan/);
    expect(() => openBackup(Buffer.from("not a backup at all, just some bytes here"), "a-strong-passphrase")).toThrow(/zaxira fayli emas/);
    expect(() => sealBackup(sample, "short")).toThrow(/kamida 12/);
  });

  it("refuses a file from a newer format", () => {
    const newer = sealBackup({ ...sample, version: 99 }, "a-strong-passphrase");
    expect(() => openBackup(newer, "a-strong-passphrase")).toThrow(/yangiroq/);
  });

  it("writes a column back as it was", () => {
    expect(columnDdl(sample.tables[0].columns[0])).toBe(`"id" character varying DEFAULT gen_random_uuid() NOT NULL`);
    expect(columnDdl(sample.tables[0].columns[1])).toBe(`"patient_number" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL`);
    expect(columnDdl({ name: 'we"ird', type: "text", notNull: false, default: null, identity: "" })).toBe(`"we""ird" text`);
  });
});
